import fs from "node:fs";
import path from "node:path";
import {
  course,
  estimatedHours,
} from "../content-src/complete-course/index.mjs";
import { createManifest } from "../content-src/complete-course/manifest.mjs";
import { requestedCrosswalk } from "../content-src/complete-course/requested-topics.mjs";

const ids = new Set(course.activities.map((a) => a.id));
const archivedIds = new Set(
  [1, 2].flatMap((v) =>
    JSON.parse(
      fs.readFileSync(`content/legacy/course-v${v}.json`, "utf8"),
    ).activities.map((a) => a.id),
  ),
);
if (ids.size !== course.activities.length)
  throw new Error("Duplicate activity IDs");
for (const activity of course.activities) {
  for (const id of activity.references || []) {
    if (!ids.has(id)) throw new Error(`Missing reference ${id}`);
  }
  if (
    activity.continueFrom &&
    !ids.has(activity.continueFrom) &&
    !archivedIds.has(activity.continueFrom)
  )
    throw Error(`Missing earlier project ${activity.continueFrom}`);
}
const manifest = createManifest(course);
manifest.requestedSyllabus = requestedCrosswalk(
  JSON.parse(fs.readFileSync("content/legacy/course-v1.json", "utf8")),
  manifest.topics,
);
if (
  manifest.requestedSyllabus.length !== 151 ||
  new Set(manifest.requestedSyllabus.map((r) => r.sourceUrl)).size !== 151
)
  throw Error("Expected 151 distinct requested syllabus entries");
fs.mkdirSync("content", { recursive: true });
for (const chapter of course.chapters) {
  const directory = path.resolve(
    "content/complete-course",
    String(chapter.number).padStart(2, "0") + "-" + chapter.slug,
  );
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(
    path.join(directory, "chapter.json"),
    JSON.stringify(chapter, null, 2),
  );
  for (const id of chapter.activityIds)
    fs.writeFileSync(
      path.join(directory, id + ".json"),
      JSON.stringify(
        course.activities.find((a) => a.id === id),
        null,
        2,
      ),
    );
}
fs.writeFileSync("content/course.json", JSON.stringify(course, null, 2));
fs.writeFileSync(
  "content/curriculum-manifest.json",
  JSON.stringify(manifest, null, 2),
);
fs.writeFileSync(
  "COURSE-COVERAGE.md",
  [
    "# Requested syllabus coverage",
    "",
    "Generated by `npm run content`. The 151 distinct linked entries are mapped below; repeated list and loop blocks are consolidated. The machine-readable manifest contains exact section, checkpoint, question-form and later-retrieval identifiers. Teaching is authored explicitly; syntax in runtime infrastructure does not count.",
    "",
    "[Full evidence and prerequisites](content/curriculum-manifest.json) · [Learning path](COURSE-REWORK-MAP.md)",
    "",
    "| Requested reference | Topic contracts | Introduction / practice |",
    "| --- | --- | --- |",
    ...manifest.requestedSyllabus.map(
      (r) =>
        `| [${r.referenceTitle.en}](${r.sourceUrl}) | ${r.topicIds.map((id) => "`" + id + "`").join(", ")} | ${[...new Set(r.evidence.map((e) => e.introduction))].join(", ")} |`,
    ),
    "",
  ].join("\n"),
);
console.log(
  `${course.activities.length} activities / ${course.chapters.length} modules / ${manifest.topics.length} topics; approximately ${estimatedHours} hours plus review. Both historical courses preserved.`,
);
